/*
 * study-order-model.js — v16 R27 alternate study orders (Botfive). Exposes window.StudyOrder (pure logic) and
 * window.V16StudyOrder (thin storage wrapper); CommonJS for tests. Design: kanji-team/R27-study-order.md;
 * UI hooks for Botfour: kanji-team/R27-study-order-hooks.md.
 *
 * Why (MARKET_RESEARCH.md §2 pain #2 "control over order and pace", backlog #11 "alternate study orders (JLPT,
 * Heisig/RTK, WaniKani, Genki)"; R26 did the "already know" half): the learner chooses the order in which a level's
 * NEW kanji are introduced. It only reorders the `planned` list that V15.pickNewLesson already receives, so every
 * rule after it is unchanged: component gating (parts still come first), look-alike / same-reading spacing, leech
 * pauses and the daily load budget. It never changes grading, ranks, reviews or which level is studied.
 *
 * Orders:
 *   'app'       the app's set order (default; pickNewLesson behaves exactly as before)
 *   'frequency' most frequent in newspapers first (KANJIDIC2 rank; unknown last)
 *   'grade'     Japanese school grade (1–6, then secondary), most frequent first within a grade
 *   'strokes'   fewest strokes first, most frequent first within a stroke count
 *   'custom'    the learner's own list (pasted: RTK/Heisig, WaniKani, Genki, a textbook index …): kanji in the
 *               list first, in list order; the rest after them in app order. No third-party order data is shipped.
 * All sorts are stable: ties keep the app order.
 *
 * Storage: 'v16:study-order' = { v: 1, order, list } (list = the custom kanji string, capped at MAX_LIST).
 * Sort keys: study-order-data.js (window.STUDY_ORDER_DATA, generated by tools/gen-study-order-data.js, ~38 KB).
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else { root.StudyOrder = api; root.V16StudyOrder = api.bind(root); }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const VERSION = 1;
  const KEY = 'v16:study-order';
  const ORDERS = ['app', 'frequency', 'grade', 'strokes', 'custom'];
  const DEFAULT = { v: VERSION, order: 'app', list: '' };
  const MAX_INPUT = 200000;   // characters read from a paste (same cap as R26 import)
  const MAX_LIST = 5000;      // kanji kept in a custom list (> all ~2,200 app kanji; also > RTK's 3,000)
  const HAN = /\p{Script=Han}/u;
  const F = { freq: 0, grade: 1, strokes: 2 };   // index in STUDY_ORDER_DATA.keys[k]

  /** Kanji of a pasted text, first-seen order, deduplicated, at most MAX_LIST, as one string. */
  function cleanList(text) {
    const seen = new Set(), out = [];
    for (const ch of String(text || '').slice(0, MAX_INPUT)) {
      if (!HAN.test(ch) || seen.has(ch)) continue;
      seen.add(ch); out.push(ch);
      if (out.length >= MAX_LIST) break;
    }
    return out.join('');
  }

  /** Parse a stored value; anything malformed or unknown becomes the default ('app'). */
  function parse(raw) {
    let o;
    try { o = typeof raw === 'string' ? JSON.parse(raw) : raw; } catch (e) { return Object.assign({}, DEFAULT); }
    if (!o || typeof o !== 'object' || !ORDERS.includes(o.order)) return Object.assign({}, DEFAULT);
    return { v: VERSION, order: o.order, list: cleanList(o.list) };
  }

  /** Sort key reader: missing data or fields → Infinity (sorts last). */
  function keyOf(data, k, field) {
    const row = data && data.keys && data.keys[k];
    const v = row ? row[F[field]] : null;
    return Number.isFinite(v) ? v : Infinity;
  }

  /** Stable sort of `list` by the given fields (each ascending); ties keep input order. */
  function sortBy(list, data, fields) {
    return list.map((k, i) => ({ k, i })).sort((a, b) => {
      for (const f of fields) { const d = keyOf(data, a.k, f) - keyOf(data, b.k, f); if (d) return d; }
      return a.i - b.i;
    }).map((x) => x.k);
  }

  /**
   * The planned list in the chosen order (a new array; the input is not changed).
   * @param {string[]} planned  the level's planned kanji (app order)
   * @param {{order: string, list?: string}} setting  from parse()
   * @param {object} data  window.STUDY_ORDER_DATA (needed for frequency/grade/strokes; without it → app order)
   * @returns {string[]}
   */
  function plan(planned, setting, data) {
    const list = Array.isArray(planned) ? planned.slice() : [];
    const s = parse(setting);
    switch (s.order) {
      case 'frequency': return data ? sortBy(list, data, ['freq']) : list;
      case 'grade': return data ? sortBy(list, data, ['grade', 'freq']) : list;
      case 'strokes': return data ? sortBy(list, data, ['strokes', 'freq']) : list;
      case 'custom': {
        const pos = new Map([...s.list].map((k, i) => [k, i]));
        const inList = list.filter((k) => pos.has(k)).sort((a, b) => pos.get(a) - pos.get(b));
        return inList.concat(list.filter((k) => !pos.has(k)));
      }
      default: return list;   // 'app'
    }
  }

  /** For the settings preview: how many of a custom list are in the app (`isKanji`) and the first few in order. */
  function customSummary(text, isKanji, show = 12) {
    const list = [...cleanList(text)];
    const inApp = list.filter((k) => isKanji(k));
    return { total: list.length, inApp: inApp.length, notInApp: list.length - inApp.length, first: inApp.slice(0, show) };
  }

  /** Browser wrapper: the saved setting, a setter, and plan() for V15.pickNewLesson. */
  function bind(win) {
    const store = () => win.localStorage;
    const set = (key, v) => (win.DataSafety && win.DataSafety.safeSet ? win.DataSafety.safeSet(store(), key, v) : store().setItem(key, v));
    const fire = (detail) => { try { win.dispatchEvent(new win.CustomEvent('v16:study-order', { detail })); } catch (e) { /* tests */ } };
    const isKanji = (k) => !!(win.STUDY_ORDER_DATA && win.STUDY_ORDER_DATA.keys[k]);
    function get() { try { return parse(store().getItem(KEY)); } catch (e) { return Object.assign({}, DEFAULT); } }
    return {
      KEY, ORDERS, MAX_INPUT, MAX_LIST,
      /** {v, order, list} — always valid ('app' when unset). */
      get,
      /**
       * Save the order (and, for 'custom', the pasted text). Returns the saved setting, or null for an unknown order
       * or a custom list with no kanji. Fires 'v16:study-order' {order}.
       */
      set(order, text) {
        if (!ORDERS.includes(order)) return null;
        const list = order === 'custom' ? cleanList(text) || get().list : get().list;   // keep a saved list when switching away
        if (order === 'custom' && !list) return null;
        const s = { v: VERSION, order, list };
        set(KEY, JSON.stringify(s));
        fire({ order });
        return s;
      },
      /** Preview of a custom paste (nothing saved). */
      customSummary: (text) => customSummary(text, isKanji),
      /** Reorder a planned list by the saved setting (called by V15.pickNewLesson). */
      plan: (planned) => plan(planned, get(), win.STUDY_ORDER_DATA),
    };
  }

  return { VERSION, KEY, ORDERS, MAX_INPUT, MAX_LIST, cleanList, parse, plan, customSummary, bind };
});
