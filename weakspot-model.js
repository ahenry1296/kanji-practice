/*
 * weakspot-model.js — v16 R24 weak-spot diagnosis (Botfive). Pure: no DOM, no storage. Exposes window.WeakSpotModel;
 * CommonJS for tests. The browser glue is v16-weakspot.js; the design is kanji-team/R24-weakspot.md.
 *
 * Idea (MARKET_RESEARCH.md §4 gap #2 / backlog #9; V16_PLAN.md F7–F9): every graded stroke is one attempt at
 *   - a COMPONENT: the top-level part that owns the stroke (data `parts[{g, from, to}]`) and, when B3's nested groups
 *     are loaded (window.KANJI_GROUPS, read-only), the innermost nested group too (e.g. 舌 inside 話);
 *   - a STROKE TYPE: from window.HOOK_CATEGORIES[char] (hook-categories.js, generated by kanji-data/gen_hook_categories.py
 *     from KanjiVG kvg:type + hook detection; one code per stroke). Codes are grouped into 8 learner-facing types
 *     (TYPE_OF below). No HOOK_CATEGORIES entry → type 'unknown' (we do NOT guess a type from the drawn shape).
 * A miss is also logged with its reject reason. Weak spots are components / types whose recent miss rate is high,
 * measured with recency decay, a minimum amount of evidence and relative to the learner's own overall miss rate.
 *
 * Nothing here changes grading: the glue only observes checkStroke's verdict after the fact.
 *
 * State (stored by the glue under 'v16:weakspot', exported with the other v16: keys):
 *   { v: 1, all: Agg, comp: {g: Agg}, type: {code: Agg}, hist: [Miss…], weak: [id…] }
 *   Agg  = { a: decayed attempts, m: decayed misses, n: raw attempts (never decays), at: ms of the last update }
 *   Miss = { t: ms, k: kanji, s: 0-based stroke in the kanji, c: top-level component|null, g: nested group|null,
 *            ty: stroke type, r: reason, d: checker detail (verdict.shape, ≤ 40 chars)|null }
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.WeakSpotModel = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const VERSION = 1;
  const HALF_LIFE_DAYS = 7;     // same as diagnosis-model.js: a miss counts half after a week
  const MIN_ATTEMPTS = 6;       // decayed attempts needed before a component/type may be called weak
  const MIN_MISSES = 3;         // decayed misses needed, so one bad day of 2 slips is not a "weak spot"
  const MIN_RATE = 0.3;         // smoothed miss rate needed …
  const REL_RATE = 1.5;         // … and at least 1.5× the learner's own overall miss rate (a sloppy writer is not weak everywhere)
  const PRIOR = 2;              // smoothing: rate = m / (a + PRIOR), so 2 misses in 2 tries is 0.5, not 1.0
  const MAX_WEAK = 3;           // at most this many weak spots are reported / practised at once
  const MAX_HIST = 300;         // miss log ring size (newest kept)
  const MAX_COMP = 400;         // tracked components (least-attempted dropped first)
  const DAY_MS = 864e5;

  /** HOOK_CATEGORIES code → learner-facing stroke type (HOOK_RULES.md §Categories). */
  const TYPE_OF = {
    h: 'horizontal', v: 'vertical', d: 'dot', r: 'rise',
    l: 'left-sweep', s: 'right-sweep', b: 'turn',
    V: 'hook', C: 'hook', H: 'hook', U: 'hook', F: 'hook',
    k: 'kana', K: 'kana',
  };
  /** Short names for messages ("hooks", "turns"). */
  const TYPE_LABEL = {
    horizontal: 'horizontal strokes', vertical: 'vertical strokes', dot: 'dots', rise: 'rising strokes',
    'left-sweep': 'left sweeps (ノ)', 'right-sweep': 'right sweeps (㇏)', turn: 'turns (corners)', hook: 'hooks (はね)',
    kana: 'kana strokes', unknown: 'strokes',
  };

  const isObj = (v) => Boolean(v) && typeof v === 'object' && !Array.isArray(v);
  const num = (v, d) => (Number.isFinite(Number(v)) ? Number(v) : d);

  /** Stroke type of stroke `i` (0-based) of `char`, from the HOOK_CATEGORIES table (string, one code per stroke). */
  function strokeType(char, i, table) {
    const codes = table && typeof table[char] === 'string' ? table[char] : '';
    return TYPE_OF[codes[i]] || 'unknown';
  }

  /**
   * Reject reason of a checkStroke verdict, as a small fixed vocabulary:
   *   'order' (Wrong order) · 'redo-first' (Redo first) · 'shape' (Shape; detail in verdict.shape) ·
   *   'position' (any other message: placement / size / direction — checkStroke's own text is kept in `d`).
   */
  function reasonOf(verdict) {
    if (!verdict || verdict.ok) return null;
    if (verdict.redoFirst || verdict.msg === 'Redo first') return 'redo-first';
    if (verdict.msg === 'Wrong order') return 'order';
    if (verdict.msg === 'Shape' || verdict.shape) return 'shape';
    return 'position';
  }
  function detailOf(verdict) {
    const d = verdict && (typeof verdict.shape === 'string' ? verdict.shape : typeof verdict.msg === 'string' ? verdict.msg : null);
    return d ? d.slice(0, 40) : null;
  }

  /**
   * Which components own stroke `s` of kanji entry `entry`: {c: top-level part glyph|null, g: innermost nested group|null}.
   * entry.parts = [{g, from, to}] (inclusive, 0-based). groups = KANJI_GROUPS[kanji] = [{g, from, to, depth}].
   * A nested group equal to the top-level part is ignored (same as diagnosis-model.js R22).
   */
  function componentsOfStroke(entry, s, groups) {
    let c = null, g = null, depth = -1;
    for (const p of (entry && Array.isArray(entry.parts) ? entry.parts : [])) {
      if (p && typeof p.g === 'string' && s >= p.from && s <= p.to) { c = p.g; break; }
    }
    for (const grp of (Array.isArray(groups) ? groups : [])) {
      if (!grp || typeof grp.g !== 'string' || grp.g === c) continue;
      if (s >= grp.from && s <= grp.to && num(grp.depth, 0) > depth) { g = grp.g; depth = num(grp.depth, 0); }
    }
    return { c, g };
  }

  function empty() { return { v: VERSION, all: agg(), comp: {}, type: {}, hist: [], weak: [] }; }
  function agg() { return { a: 0, m: 0, n: 0, at: 0 }; }

  /** Parse stored state; anything malformed is replaced by an empty part (never throws). */
  function sanitize(raw) {
    let s = raw;
    if (typeof s === 'string') { try { s = JSON.parse(s); } catch (_) { s = null; } }
    const out = empty();
    if (!isObj(s)) return out;
    const fixAgg = (x) => (isObj(x) ? { a: Math.max(0, num(x.a, 0)), m: Math.max(0, num(x.m, 0)), n: Math.max(0, num(x.n, 0)), at: num(x.at, 0) } : agg());
    out.all = fixAgg(s.all);
    for (const key of ['comp', 'type']) if (isObj(s[key])) for (const id in s[key]) out[key][id] = fixAgg(s[key][id]);
    if (Array.isArray(s.hist)) out.hist = s.hist.filter((h) => isObj(h) && typeof h.k === 'string').slice(-MAX_HIST);
    if (Array.isArray(s.weak)) out.weak = s.weak.filter((w) => typeof w === 'string').slice(0, MAX_WEAK * 2);
    return out;
  }

  /** Decay an Agg to time `now` (half-life HALF_LIFE_DAYS). Returns a new object. */
  function decayed(x, now) {
    const dt = Math.max(0, (now - num(x.at, now)) / DAY_MS);
    const f = Math.pow(0.5, dt / HALF_LIFE_DAYS);
    return { a: x.a * f, m: x.m * f, n: x.n, at: now };
  }
  function bump(map, id, miss, now) {
    const x = map[id] ? decayed(map[id], now) : agg();
    x.a += 1; x.n += 1; if (miss) x.m += 1; x.at = now;
    map[id] = x;
  }

  /**
   * Record one graded stroke. ev = {kanji, stroke, entry, groups, types, verdict, now}:
   *   kanji   the character written; stroke 0-based index in that character;
   *   entry   its data entry (for parts); groups KANJI_GROUPS[kanji] or null; types HOOK_CATEGORIES table or null.
   * Mutates and returns `state`. Returns the Miss logged (or null) as state.lastMiss for the caller.
   */
  function record(state, ev) {
    const now = num(ev.now, Date.now());
    const miss = !!(ev.verdict && !ev.verdict.ok);
    const { c, g } = componentsOfStroke(ev.entry, ev.stroke, ev.groups);
    const ty = strokeType(ev.kanji, ev.stroke, ev.types);
    bump(state, 'all', miss, now);   // state.all is an Agg keyed 'all' on state itself
    if (c) bump(state.comp, c, miss, now);
    if (g) bump(state.comp, g, miss, now);
    bump(state.type, ty, miss, now);
    state.lastMiss = null;
    if (miss) {
      const m = { t: now, k: ev.kanji, s: ev.stroke, c, g, ty, r: reasonOf(ev.verdict), d: detailOf(ev.verdict) };
      state.hist.push(m);
      if (state.hist.length > MAX_HIST) state.hist.splice(0, state.hist.length - MAX_HIST);
      state.lastMiss = m;
    }
    capComponents(state);
    return state;
  }
  /** Keep at most MAX_COMP components: drop those with the fewest decayed attempts. */
  function capComponents(state) {
    const ids = Object.keys(state.comp);
    if (ids.length <= MAX_COMP) return;
    ids.sort((x, y) => state.comp[x].a - state.comp[y].a).slice(0, ids.length - MAX_COMP).forEach((id) => { delete state.comp[id]; });
  }

  /** Smoothed miss rate of an Agg. */
  const rateOf = (x) => x.m / (x.a + PRIOR);

  /**
   * Current weak spots, worst first: [{kind:'component'|'type', id, label, rate, misses, attempts, reasons:{r:n},
   * examples:[{kanji, stroke}]}] (examples: last 3 misses, 0-based strokes). A spot is weak when, after decay:
   * attempts ≥ MIN_ATTEMPTS, misses ≥ MIN_MISSES, rate ≥ MIN_RATE and rate ≥ REL_RATE × overall rate.
   * 'unknown' stroke type is never a weak spot (no data to say what the stroke was).
   */
  function weakSpots(state, now = Date.now(), opts = {}) {
    const s = sanitize(state);
    const overall = rateOf(decayed(s.all, now));
    const limit = num(opts.limit, MAX_WEAK);
    const out = [];
    const consider = (kind, id, x0) => {
      const x = decayed(x0, now);
      const rate = rateOf(x);
      if (x.a < MIN_ATTEMPTS || x.m < MIN_MISSES || rate < MIN_RATE || rate < REL_RATE * overall) return;
      const mine = s.hist.filter((h) => (kind === 'component' ? h.c === id || h.g === id : h.ty === id));
      const reasons = {};
      mine.forEach((h) => { reasons[h.r] = (reasons[h.r] || 0) + 1; });
      out.push({ kind, id, label: kind === 'component' ? id : TYPE_LABEL[id] || id, rate: Math.round(rate * 1000) / 1000,
        misses: Math.round(x.m * 100) / 100, attempts: Math.round(x.a * 100) / 100, reasons,
        examples: mine.slice(-3).reverse().map((h) => ({ kanji: h.k, stroke: h.s })) });
    };
    for (const id in s.comp) consider('component', id, s.comp[id]);
    for (const id in s.type) if (id !== 'unknown') consider('type', id, s.type[id]);
    // components before types at equal rate (they are more actionable: V16_PLAN F8/F9)
    out.sort((x, y) => y.rate - x.rate || (x.kind === y.kind ? 0 : x.kind === 'component' ? -1 : 1));
    return out.slice(0, limit);
  }
  const spotId = (w) => w.kind + ':' + w.id;

  /** Plain-text message for one weak spot, e.g. 'Weak spot: 寺 (4 of the last 9 tries missed)'. */
  function message(w) {
    if (!w) return null;
    const tries = Math.round(w.attempts), miss = Math.round(w.misses);
    return 'Weak spot: ' + w.label + ' (' + miss + ' of the last ' + tries + ' tries missed)';
  }

  /**
   * Update state.weak with the current weak spots and return those that are NEW since the last call (these trigger the
   * 'v16:diagnosis' event; a spot that recovers and becomes weak again later counts as new again).
   */
  function newlyWeak(state, now = Date.now()) {
    const cur = weakSpots(state, now);
    const before = new Set(state.weak || []);
    state.weak = cur.map(spotId);
    return cur.filter((w) => !before.has(spotId(w)));
  }

  /**
   * Short targeted review set (unscored practice; never touches FSRS), Alexander's component-first flow
   * (V16_PLAN F8/F9): for each weak spot, first practise the COMPONENT on its own (in the kanji where it was missed),
   * then write FAMILY MEMBERS the learner already studies that share it.
   *   data = {family(g) → [{k, status}], practisable(kanji, g) → bool, known(k) → bool}  (all optional functions)
   * Steps: {kind:'component', kanji, component, why} | {kind:'kanji', kanji, why}; at most opts.limit (8) steps,
   * at most opts.perSpot (3) family members per spot, no duplicate kanji.
   * Stroke-type spots: practise the components where that type was missed most, then those kanji.
   */
  function practiceSet(state, data = {}, opts = {}) {
    const now = num(opts.now, Date.now());
    const limit = num(opts.limit, 8), perSpot = num(opts.perSpot, 3);
    const s = sanitize(state);
    const spots = opts.spots || weakSpots(s, now);
    const steps = [], usedKanji = new Set(), usedComp = new Set();
    const practisable = typeof data.practisable === 'function' ? data.practisable : () => true;
    const known = typeof data.known === 'function' ? data.known : () => true;
    const family = typeof data.family === 'function' ? data.family : () => [];
    const push = (st) => { if (steps.length < limit) steps.push(st); };
    const compStep = (g, why) => {
      if (usedComp.has(g)) return;
      // the kanji where g was missed most recently and that can be practised as a part
      const h = s.hist.slice().reverse().find((x) => (x.c === g || x.g === g) && practisable(x.k, g));
      if (!h) return;
      usedComp.add(g);
      push({ kind: 'component', kanji: h.k, component: g, why });
    };
    const familySteps = (g, why) => {
      let n = 0;
      for (const e of family(g) || []) {
        const k = e && (e.k || e);
        if (n >= perSpot || typeof k !== 'string' || usedKanji.has(k) || !known(k)) continue;
        usedKanji.add(k); n += 1;
        push({ kind: 'kanji', kanji: k, why });
      }
    };
    for (const w of spots) {
      const why = spotId(w);
      if (w.kind === 'component') { compStep(w.id, why); familySteps(w.id, why); continue; }
      // stroke type: components where this type was missed, most misses first
      const count = {};
      s.hist.filter((h) => h.ty === w.id && h.c).forEach((h) => { count[h.c] = (count[h.c] || 0) + 1; });
      const comps = Object.keys(count).sort((x, y) => count[y] - count[x]).slice(0, 2);
      comps.forEach((g) => compStep(g, why));
      s.hist.slice().reverse().filter((h) => h.ty === w.id).forEach((h) => {
        if (!usedKanji.has(h.k) && known(h.k) && steps.filter((x) => x.why === why && x.kind === 'kanji').length < perSpot) {
          usedKanji.add(h.k); push({ kind: 'kanji', kanji: h.k, why });
        }
      });
    }
    return steps;
  }

  return {
    VERSION, HALF_LIFE_DAYS, MIN_ATTEMPTS, MIN_MISSES, MIN_RATE, REL_RATE, PRIOR, MAX_WEAK, MAX_HIST, MAX_COMP,
    TYPE_OF, TYPE_LABEL, strokeType, reasonOf, componentsOfStroke, empty, sanitize, decayed, record, weakSpots,
    newlyWeak, message, practiceSet, spotId,
  };
});
